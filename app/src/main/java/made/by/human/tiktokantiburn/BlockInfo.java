package made.by.human.tiktokantiburn;

public class BlockInfo {
    int width;
    int height;
    int x;
    int y;

    public BlockInfo(int width, int height, int x, int y) {
        this.width = width;
        this.height = height;
        this.x = x;
        this.y = y;
    }

    public BlockInfo() {}
}

